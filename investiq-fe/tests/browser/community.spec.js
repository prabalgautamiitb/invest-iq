import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { verifiedAccount } from './helpers.js';

test('community posts, replies, groups, polls and private saves persist',async({page,request,browser})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('investiq-demo-v1',JSON.stringify({posts:[{text:'A fake local community import'}]})));
  await verifiedAccount(page,request,`community-${randomUUID()}@example.com`);
  await page.goto('/#/social');
  await expect(page.getByRole('heading',{name:'Share a thought or question'})).toBeVisible();
  await expect(page.locator('.main')).not.toContainText('A fake local community import');
  const text='Diversification question '+randomUUID();
  await page.getByLabel('Your post',{exact:true}).fill(text);
  await page.getByRole('button',{name:'Publish post',exact:true}).click();
  const card=page.locator('[data-community-post]').filter({hasText:text});
  await expect(card).toHaveCount(1);
  await card.getByRole('button',{name:'Save',exact:true}).click();
  await card.getByRole('button',{name:'Like · 0',exact:true}).click();
  await expect(card.getByRole('button',{name:'Unlike · 1',exact:true})).toBeVisible();
  await card.getByRole('link',{name:'0 replies',exact:true}).click();
  await page.getByLabel('Your reply',{exact:true}).fill('This is a genuine saved reply.');
  await page.getByRole('button',{name:'Reply',exact:true}).click();
  await expect(page.getByText('This is a genuine saved reply.',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('This is a genuine saved reply.',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'All discussions',exact:true}).click();
  await page.getByRole('button',{name:'Saved',exact:true}).click();
  await expect(card).toHaveCount(1);
  await page.getByRole('button',{name:'All',exact:true}).click();
  await page.getByText('Create a public group',{exact:true}).click();
  const group='Learning circle '+randomUUID();
  await page.getByLabel('Group name',{exact:true}).fill(group);
  await page.getByLabel('Description',{exact:true}).fill('Public questions about simulated portfolios');
  await page.getByRole('button',{name:'Create group',exact:true}).click();
  const groupRow=page.locator('.settingsrow').filter({hasText:group});
  await expect(groupRow).toContainText('1 member');
  await groupRow.getByRole('button',{name:'View group',exact:true}).click();
  await page.getByLabel('Post category',{exact:true}).selectOption('poll');
  const poll='Poll '+randomUUID();
  await page.getByLabel('Your post',{exact:true}).fill(poll);
  await page.getByLabel('Poll options (one per line, 2–6)',{exact:true}).fill('Diversify\nConcentrate');
  const keys=[];let interrupted=false;
  await page.route('**/api/v1/community/posts',async route=>{
    if(route.request().method()!=='POST')return route.continue();
    keys.push(route.request().headers()['idempotency-key']);
    if(!interrupted){interrupted=true;const accepted=await route.fetch();expect(accepted.status()).toBe(201);return route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{message:'Post response interrupted'}})});}
    return route.continue();
  });
  await page.getByRole('button',{name:'Publish post',exact:true}).click();
  await expect(page.locator('.main').getByRole('status')).toContainText('Post response interrupted');
  await expect(page.getByLabel('Your post',{exact:true})).toHaveValue(poll);
  await expect(page.getByLabel('Poll options (one per line, 2–6)',{exact:true})).toHaveValue('Diversify\nConcentrate');
  await page.getByRole('button',{name:'Publish post',exact:true}).click();
  const pollCard=page.locator('[data-community-post]').filter({hasText:poll});
  await expect(pollCard).toHaveCount(1);expect(keys).toHaveLength(2);expect(keys[0]).toBe(keys[1]);
  await pollCard.getByRole('button',{name:'Diversify 0 votes',exact:true}).click();
  await expect(pollCard).toContainText('1 vote · Your vote');
  await page.reload();
  await expect(pollCard).toContainText('1 vote · Your vote');
  const context=await browser.newContext();const guest=await context.newPage();
  await guest.goto('/#/social');
  const guestCard=guest.locator('[data-community-post]').filter({hasText:poll});
  await expect(guestCard).toContainText('Private learner');
  await expect(guestCard).not.toContainText('Your vote');
  await expect(guestCard).toContainText('1 total votes');
  await expect(guestCard.getByRole('button',{name:'Save',exact:true})).toHaveCount(0);
  await guest.setViewportSize({width:390,height:844});
  expect(await guest.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await context.close();expect(errors).toEqual([]);
});

test('community errors retry and administrators moderate reported content',async({page,request})=>{
  await page.route('**/api/v1/community/posts?*',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{message:'Community feed unavailable'}})}));
  await page.goto('/#/social');
  await expect(page.getByRole('alert')).toContainText('Community feed unavailable');
  await page.unroute('**/api/v1/community/posts?*');
  await page.getByRole('button',{name:'Retry community',exact:true}).click();
  await expect(page.getByRole('link',{name:'Sign in to join the discussion',exact:true})).toBeVisible();
  await verifiedAccount(page,request,`moderator-${randomUUID()}@example.com`);
  const user=await page.evaluate(async()=> (await (await fetch('/api/v1/me')).json()).id);
  expect((await request.post(`http://127.0.0.1:8081/__browser__/admin/${user}`,{headers:{'X-Investiq-Browser-Test':'local-disposable-only'}})).ok()).toBeTruthy();
  await page.reload();await page.goto('/#/social');
  const text='Content for moderator review '+randomUUID();
  await page.getByLabel('Your post',{exact:true}).fill(text);
  await page.getByRole('button',{name:'Publish post',exact:true}).click();
  const card=page.locator('[data-community-post]').filter({hasText:text});
  await card.getByRole('button',{name:'Report',exact:true}).click();
  await page.getByLabel('Reason',{exact:true}).fill('Please review this discussion.');
  await page.getByRole('button',{name:'Submit report',exact:true}).click();
  await page.getByRole('link',{name:'Moderation',exact:true}).click();
  await page.locator('article').filter({hasText:text}).getByRole('button',{name:'Review content',exact:true}).click();
  await page.getByLabel('Reason',{exact:true}).fill('Reviewed content hidden for this test.');
  await page.getByRole('button',{name:'Record decision',exact:true}).click();
  await expect(page.locator('article').filter({hasText:text})).toContainText('Content hidden');
  await page.getByRole('link',{name:'All discussions',exact:true}).click();
  await expect(card).toHaveCount(0);
});
