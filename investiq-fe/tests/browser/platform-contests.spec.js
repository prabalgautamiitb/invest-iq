import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { verifiedAccount } from './helpers.js';

const harness={'X-Investiq-Browser-Test':'local-disposable-only'};
async function clock(request,at){const r=await request.post('http://127.0.0.1:8081/__browser__/clock',{headers:harness,data:{at}});expect(r.ok()).toBeTruthy();}

test('admin publishes an InvestIQ contest and another learner joins, submits and follows standings',async({page,request,browser})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await clock(request,'2026-10-14T13:00:00Z');
  let learnerContext;
  try {
    await verifiedAccount(page,request,`platform-admin-${randomUUID()}@example.com`);
    const user=await page.evaluate(async()=> (await (await fetch('/api/v1/me')).json()));
    const promotion=await request.post('http://127.0.0.1:8081/__browser__/admin/'+user.id,{headers:harness});expect(promotion.ok()).toBeTruthy();
    await page.goto('/#/contests');
    await page.reload();
    await expect(page.getByRole('navigation',{name:'Admin navigation'})).toBeVisible();
    await page.getByRole('link',{name:'Add InvestIQ contest',exact:true}).click();
    await page.getByLabel('Contest name',{exact:true}).fill('InvestIQ shared public challenge');
    await page.getByLabel('Contest ends (IST)',{exact:true}).fill('2026-10-16T15:30');
    await page.getByRole('button',{name:'Save contest draft',exact:true}).click();
    await expect(page.getByRole('button',{name:'Publish and freeze rules',exact:true})).toBeVisible();
    const id=new URL(page.url()).hash.split('/')[2];
    await page.getByRole('button',{name:'Publish and freeze rules',exact:true}).click();
    await expect(page.getByText('InvestIQ public contest',{exact:true})).toBeVisible();
    await page.goto('/#/leaderboard/'+id);
    await expect(page).toHaveURL(/#\/contests\/admin$/);
    await expect(page.getByRole('link',{name:'My performance',exact:true})).toHaveCount(0);
    learnerContext=await browser.newContext();const learner=await learnerContext.newPage();
    await learner.goto('/#/contests');
    await learner.getByRole('button',{name:'InvestIQ',exact:true}).click();
    await expect(learner.getByRole('heading',{name:'InvestIQ shared public challenge',exact:true})).toBeVisible();
    await verifiedAccount(learner,request,`platform-learner-${randomUUID()}@example.com`);
    await learner.goto('/#/contests/'+id);
    learner.once('dialog',d=>d.accept());
    await learner.getByRole('button',{name:/Reserve .* join/}).click();
    await expect(learner).toHaveURL(/#\/my-contests$/);
    await learner.locator('.main').getByRole('link',{name:'Portfolio',exact:true}).click();
    await learner.getByRole('button',{name:'Use starter weights',exact:true}).click();
    await learner.getByRole('button',{name:'Save draft',exact:true}).click();
    await expect(learner.getByText('Draft saved on the server.',{exact:true})).toBeVisible();
    await learner.getByRole('button',{name:'Review saved draft',exact:true}).click();
    await expect(learner.getByRole('heading',{name:'Review server calculation',exact:true})).toBeVisible();
    await learner.getByRole('button',{name:'Confirm contest submission',exact:true}).click();
    await expect(learner.locator('#portfolio-history')).toContainText('Version 1');
    await clock(request,'2026-10-15T13:00:00Z');
    const valued=await request.post('http://127.0.0.1:8081/__browser__/value/'+id,{headers:harness});expect(valued.ok()).toBeTruthy();
    await learner.goto('/#/leaderboard/'+id);
    await expect(learner.locator('tbody tr')).toHaveCount(1);
    await expect(learner.locator('tbody')).toContainText('· you');
    await learner.getByRole('link',{name:'My performance',exact:true}).click();
    await expect(learner.getByRole('region',{name:'Portfolio allocation',exact:true})).toBeVisible();
    await learner.getByText('Portfolio details and holding values',{exact:true}).click();
    await expect(learner.getByRole('heading',{name:'Portfolio metrics',exact:true})).toBeVisible();
    expect(errors).toEqual([]);
  } finally {await learnerContext?.close();await clock(request,'2026-10-18T12:00:00Z');}
});

test('regular learners cannot create or manage platform contests',async({page,request})=>{
  await verifiedAccount(page,request,`platform-denied-${randomUUID()}@example.com`);
  await page.goto('/#/contests');
  await expect(page.getByRole('link',{name:'Create contest',exact:true})).toBeVisible();
  await expect(page.getByRole('link',{name:'Manage InvestIQ contests',exact:true})).toHaveCount(0);
  await page.goto('/#/contests/create-platform');
  await expect(page.locator('.main')).toContainText('Administrator access is required.');
  await page.goto('/#/contests/admin');
  await expect(page.locator('.main')).toContainText('Administrator access is required.');
});

test('admin creation explains invalid date order, preserves edits and accepts a corrected schedule',async({page,request})=>{
  await clock(request,'2026-10-14T13:00:00Z');
  try {
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await verifiedAccount(page,request,`platform-schedule-${randomUUID()}@example.com`);
  const user=await page.evaluate(async()=>(await (await fetch('/api/v1/me')).json()));
  expect((await request.post('http://127.0.0.1:8081/__browser__/admin/'+user.id,{headers:harness})).ok()).toBe(true);
  await page.goto('/#/contests/create-platform');
  await page.reload();
  const opens=page.getByLabel('Entry opens (IST)',{exact:true});
  const closes=page.getByLabel('Entry closes (IST)',{exact:true});
  const starts=page.getByLabel('Contest starts (IST)',{exact:true});
  const ends=page.getByLabel('Contest ends (IST)',{exact:true});
  await page.getByLabel('Contest name',{exact:true}).fill('Schedule validation regression');
  await opens.fill('2026-10-26T18:30');
  await closes.fill('2026-10-26T09:10');
  await starts.fill('2026-10-27T09:15');
  await ends.fill('2026-10-30T15:30');
  let posts=0;page.on('request',request=>{if(request.method()==='POST'&&new URL(request.url()).pathname==='/api/v1/admin/contests')posts++;});
  await page.getByRole('button',{name:'Save contest draft',exact:true}).click();
  await expect(page.locator('[data-contest-form-error]')).toContainText('Entry opens must be before entry closes.');
  await expect(opens).toHaveAttribute('aria-invalid','true');
  await expect(closes).toHaveAttribute('aria-invalid','true');
  await expect(opens).toBeFocused();
  expect(posts).toBe(0);
  await expect(opens).toHaveValue('2026-10-26T18:30');
  await expect(starts).toHaveValue('2026-10-27T09:15');
  await opens.fill('2026-10-26T06:30');
  await opens.press('Tab');
  await expect(opens).not.toHaveAttribute('aria-invalid','true');
  await expect(page.locator('[data-contest-form-error]')).toContainText('no prices for 2026-10-27');
  await expect(page.locator('[data-simulation-coverage]')).toContainText('2026-10-16');
  await page.getByRole('button',{name:'Save contest draft',exact:true}).click();
  expect(posts).toBe(0);
  await opens.fill('2026-10-14T18:30');
  await closes.fill('2026-10-15T09:10');
  await starts.fill('2026-10-15T09:15');
  await ends.fill('2026-10-16T15:30');
  await ends.press('Tab');
  await expect(page.locator('[data-contest-form-error]')).toHaveText('');
  await page.route('**/api/v1/admin/contests',route=>route.fulfill({status:422,json:{error:{code:'validation_error',message:'Entry closes must be before the contest starts.',details:[{location:['body','starts_at'],type:'contest_lock_order',message:'Entry closes must be before the contest starts.'}]}}}));
  await page.getByRole('button',{name:'Save contest draft',exact:true}).click();
  await expect(starts).toBeFocused();
  await expect(starts).toHaveAttribute('aria-invalid','true');
  await expect(page.locator('[data-contest-form-error]')).toContainText('Entry closes must be before the contest starts.');
  await expect(opens).toHaveValue('2026-10-14T18:30');
  await page.unroute('**/api/v1/admin/contests');
  await page.getByRole('button',{name:'Save contest draft',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Schedule validation regression',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Publish and freeze rules',exact:true})).toBeVisible();
  const publish=page.getByRole('button',{name:'Publish and freeze rules',exact:true});
  await page.route('**/api/v1/contests/*/transitions',route=>route.fulfill({status:422,json:{error:{code:'scenario_coverage_missing',message:'This environment supports simulation sessions from 2026-10-14 through 2026-10-16.'}}}));
  await publish.click();
  await expect(page.getByRole('alert').filter({has:page.getByRole('heading',{name:'Contest could not be updated'})})).toContainText('through 2026-10-16');
  await expect(page.getByLabel('Contest starts (IST)',{exact:true})).toHaveValue('2026-10-15T09:15');
  await page.unroute('**/api/v1/contests/*/transitions');
  await publish.click();
  await expect(page.getByRole('button',{name:'Publish and freeze rules',exact:true})).toHaveCount(0);
  expect(errors).toEqual([]);
  } finally {await clock(request,'2026-10-18T12:00:00Z');}
});
